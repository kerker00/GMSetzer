#!/usr/bin/env python3
"""Generate dependency-free tables from pinned swift-cmark entities and official Unicode data.

Source revision 08ddb528923cc1a6527e02b7a1aee9e516ca749a; see Data/cmark-COPYING.
The entity table contains the 2,125 semicolon-terminated HTML5 names accepted
by CommonMark (the WHATWG list also has 106 legacy names without semicolons).
"""
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'Scripts' / 'Data'

def literal(text):
    return '"' + ''.join('\\u{%X}' % ord(c) for c in text) + '"'

def generate():
    entities = (DATA / 'cmark-entities.inc').read_bytes()
    folds = (DATA / 'CaseFolding-17.0.0.txt').read_bytes()
    header = ('// Generated by Scripts/generate_inline_tables.py; do not edit.\n'
              '// Entities: swift-cmark 08ddb528923cc1a6527e02b7a1aee9e516ca749a, BSD-2.\n'
              '// Full case folding: Unicode 17.0.0, Unicode License V3; see NOTICE.\n'
              '// Copyright (c) 2014 John MacFarlane; see NOTICE and Scripts/Data/cmark-COPYING.\n'
              f'// Entity input SHA-256: {hashlib.sha256(entities).hexdigest()}\n'
              f'// Case-fold input SHA-256: {hashlib.sha256(folds).hexdigest()}\n\n')
    rows = re.findall(r'\{\(unsigned char\*\)"([^"]+)", \{([\d, ]+)\}\}', entities.decode())
    assert len(rows) == 2125
    lines = [header, 'internal enum InlineTables {\n', '    static let entities: [String: String] = [\n']
    for name, values in rows:
        text = bytes(int(x) for x in values.split(',') if int(x)).decode()
        lines.append(f'        "{name}": {literal(text)},\n')
    lines.append('    ]\n\n    static let caseFold: [UInt32: String] = [\n')
    mappings = {}
    for row in folds.decode().splitlines():
        row = row.split('#', 1)[0].strip()
        if not row:
            continue
        key, status, values, _ = [part.strip() for part in row.split(';')]
        if status in ('C', 'F'):
            mappings[int(key, 16)] = ''.join(chr(int(v, 16)) for v in values.split())
    assert len(mappings) == 1585
    for key, value in sorted(mappings.items()):
        lines.append(f'        0x{key:04X}: {literal(value)},\n')
    lines.append('    ]\n}\n')
    return ''.join(lines)

if __name__ == '__main__':
    (ROOT / 'Sources' / 'SetzerParser' / 'InlineTables.swift').write_text(generate())
